    {
        if (string.IsNullOrEmpty(text)) return text;

        var sb = new StringBuilder(text.Length);
        foreach (var ch in text)
        {
            sb.Append(Map.TryGetValue(ch, out var s) ? s : ch);
        }
        return sb.ToString();
    }

